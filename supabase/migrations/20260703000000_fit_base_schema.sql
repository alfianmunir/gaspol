create unique index if not exists fit_checkins_user_date     on public.fit_checkins (user_id, log_date);
create unique index if not exists fit_settings_user_key      on public.fit_settings (user_id, key);
create index        if not exists fit_set_logs_user_date     on public.fit_set_logs (user_id, log_date);
create index        if not exists fit_food_logs_user_date    on public.fit_food_logs (user_id, log_date);
