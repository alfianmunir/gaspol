-- ============================================================
-- Gaspol — full base schema for the fit_* tables.
--
-- This is the consolidated, version-controlled schema for the dedicated
-- "gaspol" Supabase project (kxhalnjrcayzsbclfeaz). It folds together what
-- were previously the (un-tracked) base tables + the additive multi-user
-- migration, so a fresh project can be stood up from git alone.
--
-- Prototype posture: RLS is ON but every fit_* table (except fit_photos)
-- carries an open "fit anon all" policy so the app works with the anon key
-- before auth is enabled. Per-user enforcement lives in the companion
-- 20260716120100_fit_rls_enforce.sql (run AFTER auth is on).
-- ============================================================

-- ---- Tables -------------------------------------------------
create table if not exists public.fit_exercises (
  id             integer generated by default as identity primary key,
  session        text    not null,
  day_of_week    integer not null,
  sort_order     integer not null,
  name           text    not null,
  target_sets    integer not null,
  rep_low        integer not null,
  rep_high       integer not null,
  current_weight numeric,
  increment      numeric not null default 1,
  is_compound    boolean not null default false,
  rest_sec       integer default 90,
  notes          text,
  active         boolean not null default true,
  user_id        uuid references auth.users(id) on delete cascade
);

