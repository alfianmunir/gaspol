-- ---- RLS: prototype open policies (anon) --------------------
do $$
declare t text;
begin
  foreach t in array array[
    'fit_exercises','fit_set_logs','fit_foods','fit_food_logs',
    'fit_body_metrics','fit_checkins','fit_settings','fit_coach_notes'
  ] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "fit anon all" on public.%I', t);
    execute format('create policy "fit anon all" on public.%I for all to anon using (true) with check (true)', t);
  end loop;
end $$;

-- fit_photos: owner-only from day one (feature isolated).
alter table public.fit_photos enable row level security;
drop policy if exists fit_photos_owner on public.fit_photos;
create policy fit_photos_owner on public.fit_photos for all using (user_id = auth.uid()) with check (user_id = auth.uid());

-- ---- Private storage bucket for progress photos (F6) --------
insert into storage.buckets (id, name, public) values ('fit-photos','fit-photos',false) on conflict (id) do nothing;
drop policy if exists "fit-photos read own"   on storage.objects;
drop policy if exists "fit-photos write own"  on storage.objects;
drop policy if exists "fit-photos delete own" on storage.objects;
create policy "fit-photos read own"   on storage.objects for select using (bucket_id='fit-photos' and (storage.foldername(name))[1] = auth.uid()::text);
create policy "fit-photos write own"  on storage.objects for insert with check (bucket_id='fit-photos' and (storage.foldername(name))[1] = auth.uid()::text);
create policy "fit-photos delete own" on storage.objects for delete using (bucket_id='fit-photos' and (storage.foldername(name))[1] = auth.uid()::text);

-- ---- Grants (RLS still governs row visibility) --------------
grant usage on schema public to anon, authenticated;
grant all on all tables in schema public to anon, authenticated;
grant all on all sequences in schema public to anon, authenticated;
