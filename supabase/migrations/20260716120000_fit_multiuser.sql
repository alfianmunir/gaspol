-- 5b) Weekly review payload: structured stats + changelog for the app's
--     Progress screen (title/body hold the human-tone note).
alter table fit_coach_notes add column if not exists data jsonb not null default '{}'::jsonb;

-- 6) Progress photos (F6) — metadata + private storage -------------------
create table if not exists fit_photos (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null default auth.uid() references auth.users(id) on delete cascade,
  taken_on    date not null default ((now() at time zone 'Asia/Jakarta')::date),
  pose        text not null default 'front',   -- front | side | back
  storage_path text not null,                  -- object path in the 'fit-photos' bucket
  created_at  timestamptz not null default now()
);
alter table fit_photos enable row level security;
create policy fit_photos_owner on fit_photos for all using (user_id = auth.uid()) with check (user_id = auth.uid());

-- Private storage bucket for the actual image files.
insert into storage.buckets (id, name, public)
values ('fit-photos', 'fit-photos', false)
on conflict (id) do nothing;

-- Users may only touch objects under their own uid/ prefix.
create policy "fit-photos read own"   on storage.objects for select
  using (bucket_id = 'fit-photos' and (storage.foldername(name))[1] = auth.uid()::text);
create policy "fit-photos write own"  on storage.objects for insert
  with check (bucket_id = 'fit-photos' and (storage.foldername(name))[1] = auth.uid()::text);
create policy "fit-photos delete own" on storage.objects for delete
  using (bucket_id = 'fit-photos' and (storage.foldername(name))[1] = auth.uid()::text);

