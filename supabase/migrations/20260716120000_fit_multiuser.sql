-- 3) default user_id = the caller on insert ------------------------------
alter table fit_set_logs     alter column user_id set default auth.uid();
alter table fit_food_logs    alter column user_id set default auth.uid();
alter table fit_body_metrics alter column user_id set default auth.uid();
alter table fit_checkins     alter column user_id set default auth.uid();

-- 4) Row-Level Security --------------------------------------------------
-- Replace the prototype's open policies with per-user ones. Owner = user_id.
do $$
declare t text;
begin
  foreach t in array array[
    'fit_exercises','fit_set_logs','fit_food_logs','fit_body_metrics',
    'fit_checkins','fit_settings','fit_coach_notes'
  ] loop
    execute format('alter table %I enable row level security', t);
    -- drop any prototype policies (names vary; drop-if-exists the common ones)
    execute format('drop policy if exists "anon all" on %I', t);
    execute format('drop policy if exists "public" on %I', t);
    execute format('drop policy if exists %I on %I', t || '_owner', t);
    execute format($f$
      create policy %I on %I
        for all
        using (user_id = auth.uid())
        with check (user_id = auth.uid())
    $f$, t || '_owner', t);
  end loop;
end $$;

-- fit_foods: shared library (user_id null) is readable by everyone; users
-- may add/edit only their own custom foods.
alter table fit_foods enable row level security;
drop policy if exists "anon all" on fit_foods;
drop policy if exists fit_foods_read on fit_foods;
drop policy if exists fit_foods_write on fit_foods;
create policy fit_foods_read  on fit_foods for select using (user_id is null or user_id = auth.uid());
create policy fit_foods_write on fit_foods for all using (user_id = auth.uid()) with check (user_id = auth.uid());

