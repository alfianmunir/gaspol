alter table fit_set_logs      add column if not exists user_id uuid references auth.users(id) on delete cascade;
alter table fit_foods         add column if not exists user_id uuid references auth.users(id) on delete cascade; -- null = shared library
alter table fit_food_logs     add column if not exists user_id uuid references auth.users(id) on delete cascade;
alter table fit_body_metrics  add column if not exists user_id uuid references auth.users(id) on delete cascade;
